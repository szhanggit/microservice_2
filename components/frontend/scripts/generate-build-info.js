// Writes src/app/build-info.ts before every build/serve. Angular's static
// environment.<name>.ts file-replacement mechanism can't express a per-build
// value like a timestamp or git SHA, so this generates a plain TS module
// instead, sourced from process env vars set by the Dockerfile/CI (NG_APP_ENV,
// GIT_SHA) and the current time.
const fs = require('fs');
const path = require('path');

const environment = process.env.NG_APP_ENV || 'local';
const gitSha = process.env.GIT_SHA || 'dev';
const timestamp = new Date().toISOString();

const content = `// Generated by scripts/generate-build-info.js - do not edit, do not commit.
export const buildInfo = {
  environment: '${environment}',
  timestamp: '${timestamp}',
  gitSha: '${gitSha}',
};
`;

const outPath = path.join(__dirname, '..', 'src', 'app', 'build-info.ts');
fs.writeFileSync(outPath, content);
console.log(`Wrote ${outPath}`);
console.log(content);
